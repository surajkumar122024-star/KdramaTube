type Category = Drama["category"];

const COUNTRY: Record<Category, string> = {
  Korean: "South Korea",
  Chinese: "China",
  Turkish: "Turkey",
};

const make =
  (category: Category) =>
  (
    slug: string,
    title: string,
    year: number,
    rating: number,
    episodeCount: number | undefined,
    genre: string[],
    description: string,
    story: string,
    cast: [string, string][],
    whyWatch: string,
    poster?: string
  ): Drama => ({
    id: slug,
    slug,
    title,
    category,
    country: COUNTRY[category],
    year,
    rating,
    poster: poster ?? POSTER_PLACEHOLDER,
    description,
    story,
    genre,
    featured: false,
    episodeCount,
    episodes: episodeCount
      ? Array.from({ length: episodeCount }, (_, i) => ({ title: `Episode ${i + 1}`, summary: "" }))
      : undefined,
    cast: cast.map(([name, role]) => ({
      name,
      role,
      ...(ACTOR_PHOTOS[name] ? { photo: ACTOR_PHOTOS[name] } : {}),
    })),
    whyWatch,
  });

